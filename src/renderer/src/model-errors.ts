export function modelErrorMessage(error: unknown): string {
  const message = error instanceof Error ? error.message : String(error)
  const code = message.replace(/^Error: /, '').split(':')[0]!
  if (hints[code]) return `${code} · ${hints[code]}`
  if (/^(INCOMPATIBLE_|INVALID_(STREAM|TOOL|USAGE)|UNEXPECTED_TOOL|MODEL_(OUTPUT|FRAME|STREAM))/.test(code)) return `${code} · 服务返回与当前协议不兼容或超过限额；保持关闭，不执行残缺工具，不显示原始服务正文。`
  return message
}
