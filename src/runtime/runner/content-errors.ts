const correctableContentErrors = new Set([
  'CONTENT_OPERATION_INVALID', 'CONTENT_SCOPE_INVALID', 'CONTENT_SCOPE_UNREGISTERED', 'CONTENT_SCOPE_REQUIRED', 'CONTENT_SCOPE_STALE',
  'CONTENT_SHARED_SCOPE_REQUIRED', 'CONTENT_NODE_RETIRED', 'CONTENT_NODE_NOT_FOUND', 'CONTENT_ANCHOR_INVALID', 'CONTENT_BASELINE_REQUIRED',
  'CONTENT_BASELINE_STALE', 'CONTENT_DEPENDENCY_STALE', 'CONTENT_READ_INVALID', 'CONTENT_CONTAINER_INVALID', 'CONTENT_FRAGMENT_INVALID',
  'CONTENT_MOVE_CYCLE', 'CONTENT_POSITION_OVERLAP', 'CONTENT_POSITION_STALE', 'CONTENT_RANGE_INVALID', 'CONTENT_RANGE_OVERLAP', 'CONTENT_INTENT_CONFLICT',
  'WORKER_CAPABILITY_DENIED', 'CHAPTER_BASELINE_CONFLICT', 'CHAPTER_DEPENDENCY_CONFLICT', 'VERSION_CONFLICT',
  'INVALID_BUNDLE', 'BUNDLE_INVALID', 'EXPORT_FRAGMENT_INVALID', 'EXPORT_FRAGMENT_OVERLAP', 'CHAPTER_STYLE_SCOPE', 'CHAPTER_STYLE_INVALID'
])

/** An error class alone never proves that the original operation was ineffective. */
export function isCorrectableContentError(code: string): boolean { return correctableContentErrors.has(code) }
